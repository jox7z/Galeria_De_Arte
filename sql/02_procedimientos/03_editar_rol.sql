CREATE OR REPLACE PROCEDURE EDITAR_ROL(
    P_ID_USUARIO       IN NUMBER,
    P_ID_ROL           IN NUMBER,
    P_NOMBRE_ROL       IN VARCHAR2,
    P_DESCRIPCION_ROL  IN VARCHAR2,
    P_PERMISOS         IN T_LISTA_PERMISOS
)
AS
    V_EXISTE NUMBER;
BEGIN
    -- VALIDAR PERMISO
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'EDITAR_ROL');

    -- VALIDAR ROL EXISTENTE
    SELECT COUNT(*) INTO V_EXISTE
    FROM ROLES WHERE ID_ROL = P_ID_ROL;

    IF V_EXISTE = 0 THEN
        RAISE_APPLICATION_ERROR(-20060, 'El rol no existe.');
    END IF;

    -- VALIDAR NOMBRE ÚNICO
    SELECT COUNT(*) INTO V_EXISTE
    FROM ROLES
    WHERE NOMBRE_ROL = P_NOMBRE_ROL
      AND ID_ROL <> P_ID_ROL;

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20061, 'El nombre de rol ya está en uso.');
    END IF;

    -- EDITAR ROL
    UPDATE ROLES
    SET NOMBRE_ROL = P_NOMBRE_ROL,
        DESCRIPCION_ROL = P_DESCRIPCION_ROL
    WHERE ID_ROL = P_ID_ROL;

    -- BORRAR PERMISOS PREVIOS
    DELETE FROM PERMISOS_ROLES
    WHERE ID_ROL = P_ID_ROL;

    -- INSERTAR NUEVOS PERMISOS
    IF P_PERMISOS IS NOT NULL THEN
        FOR I IN 1 .. P_PERMISOS.COUNT LOOP
        
            -- Validar permiso
            SELECT COUNT(*) INTO V_EXISTE
            FROM PERMISOS
            WHERE ID_PERMISO = P_PERMISOS(I);

            IF V_EXISTE = 0 THEN
                RAISE_APPLICATION_ERROR(-20051, 'El permiso '||P_PERMISOS(I)||' no existe.');
            END IF;

            -- Insertar asociación
            INSERT INTO PERMISOS_ROLES (ID_ROL, ID_PERMISO)
            VALUES (P_ID_ROL, P_PERMISOS(I));
        END LOOP;
    END IF;

END;
