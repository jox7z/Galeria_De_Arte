CREATE OR REPLACE PROCEDURE SP_CREAR_USUARIO(
    P_ID_USUARIO        IN NUMBER,
    P_ID_ROL            IN NUMBER,
    P_NOMBRE            IN VARCHAR2,
    P_APELLIDO          IN VARCHAR2,
    P_NOMBRE_USUARIO    IN VARCHAR2,
    P_CORREO            IN VARCHAR2,
    P_IDENTIFICACION    IN VARCHAR2,
    P_TELEFONO          IN VARCHAR2,
    P_DIRECCION         IN VARCHAR2,
    P_CONTRASENA        IN VARCHAR2
)
AS
    V_EXISTE NUMBER;
BEGIN
    -- VALIDAR PERMISO
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'CREAR_USUARIO');

    -- VALIDAR ROL EXISTE
    SELECT COUNT(*) INTO V_EXISTE
    FROM ROLES
    WHERE ID_ROL = P_ID_ROL;

    IF V_EXISTE = 0 THEN
        RAISE_APPLICATION_ERROR(-20053, 'El rol indicado no existe.');
    END IF;

    -- VALIDAR NOMBRE_USUARIO ÚNICO
    SELECT COUNT(*) INTO V_EXISTE
    FROM USUARIOS
    WHERE NOMBRE_USUARIO = P_NOMBRE_USUARIO;

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20054, 'El nombre de usuario ya está en uso.');
    END IF;

    -- VALIDAR CORREO ÚNICO
    SELECT COUNT(*) INTO V_EXISTE
    FROM USUARIOS
    WHERE CORREO_ELECTRONICO = P_CORREO;

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20055, 'El correo ya está registrado.');
    END IF;

    -- VALIDAR IDENTIFICACIÓN ÚNICA
    SELECT COUNT(*) INTO V_EXISTE
    FROM USUARIOS
    WHERE IDENTIFICACION = P_IDENTIFICACION;

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20056, 'La identificación ya está en uso.');
    END IF;

    -- INSERTAR USUARIO
    INSERT INTO USUARIOS(
        ID_ROL, NOMBRE, APELLIDO, NOMBRE_USUARIO,
        CORREO_ELECTRONICO, IDENTIFICACION, TELEFONO,
        DIRECCION, ESTADO, CONTRASENA
    )
    VALUES(
        P_ID_ROL, P_NOMBRE, P_APELLIDO, P_NOMBRE_USUARIO,
        P_CORREO, P_IDENTIFICACION, P_TELEFONO,
        P_DIRECCION, 'ACTIVO', FN_HASH_CLAVE(P_NOMBRE_USUARIO, P_CONTRASENA)
    );
END;
