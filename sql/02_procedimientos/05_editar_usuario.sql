CREATE OR REPLACE PROCEDURE EDITAR_USUARIO(
    P_ID_USUARIO_ACCION IN NUMBER,
    P_ID_USUARIO        IN NUMBER,
    P_ID_ROL            IN NUMBER,
    P_NOMBRE            IN VARCHAR2,
    P_APELLIDO          IN VARCHAR2,
    P_NOMBRE_USUARIO    IN VARCHAR2,
    P_CORREO            IN VARCHAR2,
    P_IDENTIFICACION    IN VARCHAR2,
    P_TELEFONO          IN VARCHAR2,
    P_DIRECCION         IN VARCHAR2
)
AS
    V_EXISTE NUMBER;
    V_ID_USUARIO NUMBER; 
BEGIN
    SP_VALIDAR_PERMISO(P_ID_USUARIO_ACCION, 'EDITAR_USUARIO');

    BEGIN
        SELECT ID_USUARIO INTO V_ID_USUARIO
        FROM USUARIOS
        WHERE ID_USUARIO = P_ID_USUARIO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20015, 'El usuario no existe.');
    END;
    
    -- VALIDAR ROL
    SELECT COUNT(*) INTO V_EXISTE
    FROM ROLES WHERE ID_ROL = P_ID_ROL;
    IF V_EXISTE = 0 THEN
        RAISE_APPLICATION_ERROR(-20060, 'El rol no existe.');
    END IF;

    -- VALIDAR NOMBRE USUARIO ÚNICO
    SELECT COUNT(*) INTO V_EXISTE
    FROM USUARIOS
    WHERE NOMBRE_USUARIO = P_NOMBRE_USUARIO
      AND ID_USUARIO <> P_ID_USUARIO;
    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20061, 'Nombre de usuario ya está en uso.');
    END IF;

    -- VALIDAR CORREO ÚNICO
    SELECT COUNT(*) INTO V_EXISTE
    FROM USUARIOS
    WHERE CORREO_ELECTRONICO = P_CORREO
      AND ID_USUARIO <> P_ID_USUARIO;
    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20062, 'Correo ya registrado.');
    END IF;

    -- VALIDAR IDENTIFICACIÓN ÚNICA
    SELECT COUNT(*) INTO V_EXISTE
    FROM USUARIOS
    WHERE IDENTIFICACION = P_IDENTIFICACION
      AND ID_USUARIO <> P_ID_USUARIO;
    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20063, 'Identificación ya existe.');
    END IF;

    UPDATE USUARIOS
    SET ID_ROL = P_ID_ROL,
        NOMBRE = P_NOMBRE,
        APELLIDO = P_APELLIDO,
        NOMBRE_USUARIO = P_NOMBRE_USUARIO,
        CORREO_ELECTRONICO = P_CORREO,
        IDENTIFICACION = P_IDENTIFICACION,
        TELEFONO = P_TELEFONO,
        DIRECCION = P_DIRECCION
    WHERE ID_USUARIO = P_ID_USUARIO;
    EXCEPTION
       WHEN OTHERS THEN
        RAISE; -- Re-lanzar el error
END;
/
