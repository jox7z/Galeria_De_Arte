CREATE OR REPLACE PROCEDURE ACTUALIZAR_PRODUCTO(
    P_ID_USUARIO IN NUMBER,
    P_ID_PRODUCTO IN NUMBER,
    P_ID_PROVEEDOR     IN NUMBER,
    P_NOMBRE_PRODUCTO  IN VARCHAR2,
    P_TIPO_PRODUCTO    IN VARCHAR2,
    P_COSTO            IN NUMBER,
    P_PRECIO_VENTA     IN NUMBER,
    P_STOCK_MINIMO IN NUMBER
)
AS
    V_ID_PROVEEDOR NUMBER;
    V_ID_PRODUCTO NUMBER;
BEGIN
    --VALIDACIONES---
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'EDITAR_PRODUCTO');
    
    BEGIN
        SELECT ID_PRODUCTO INTO V_ID_PRODUCTO
        FROM PRODUCTOS
        WHERE ID_PRODUCTO = P_ID_PRODUCTO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20015, 'El producto no existe.');
    END;
    
    BEGIN
        SELECT ID_PROVEEDOR INTO V_ID_PROVEEDOR
        FROM PROVEEDORES
        WHERE ID_PROVEEDOR = P_ID_PROVEEDOR;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20015, 'El proveedor no existe.');
    END;
            
    -- Validar estado si se proporciona
    IF P_TIPO_PRODUCTO IS NOT NULL AND P_TIPO_PRODUCTO NOT IN ('MERCHANDISING', 'INSTRUMENTO','ADMINISTRATIVO') THEN
        RAISE_APPLICATION_ERROR(-20042, 'Tipo de producto invalido. Use: MERCHANDISING, INSTRUMENTO o ADMINISTRATIVO');
    END IF;
    
    UPDATE PRODUCTOS
    SET
        ID_PROVEEDOR = P_ID_PROVEEDOR,
        NOMBRE_PRODUCTO = P_NOMBRE_PRODUCTO,
        TIPO_PRODUCTO = P_TIPO_PRODUCTO,
        COSTO = P_COSTO,
        PRECIO_VENTA = P_PRECIO_VENTA,
        STOCK_MINIMO = P_STOCK_MINIMO
    WHERE ID_PRODUCTO = P_ID_PRODUCTO;

    EXCEPTION
       WHEN OTHERS THEN
        ROLLBACK; -- Primero hacer rollback
        RAISE; -- Re-lanzar el error
END;
/
