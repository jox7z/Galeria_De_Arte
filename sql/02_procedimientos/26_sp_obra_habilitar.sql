-- Devuelve una obra "EN MANTENIMIENTO" al estado DISPONIBLE.
CREATE OR REPLACE PROCEDURE SP_OBRA_HABILITAR(
    P_ID_USUARIO IN NUMBER,
    P_ID_OBRA    IN NUMBER
)
AS
    V_ESTADO OBRAS.ESTADO_OBRA%TYPE;
BEGIN
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'EDITAR_OBRA');

    BEGIN
        SELECT ESTADO_OBRA INTO V_ESTADO
        FROM OBRAS
        WHERE ID_OBRA = P_ID_OBRA
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20013, 'Obra no existe.');
    END;

    IF V_ESTADO = 'VENDIDA' THEN
        RAISE_APPLICATION_ERROR(-20045, 'Una obra vendida no se puede habilitar.');
    ELSIF V_ESTADO = 'DISPONIBLE' THEN
        RAISE_APPLICATION_ERROR(-20046, 'La obra ya está disponible.');
    END IF;

    UPDATE OBRAS
    SET ESTADO_OBRA = 'DISPONIBLE'
    WHERE ID_OBRA = P_ID_OBRA;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/
