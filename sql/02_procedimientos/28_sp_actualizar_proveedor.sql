CREATE OR REPLACE PROCEDURE SP_ACTUALIZAR_PROVEEDOR(
    P_ID_USUARIO        IN NUMBER,
    P_ID_PROVEEDOR      IN NUMBER,
    P_NOMBRE_PROVEEDOR  IN VARCHAR2,
    P_NOMBRE_CONTACTO   IN VARCHAR2,
    P_TELEFONO          IN VARCHAR2,
    P_DIRECCION         IN VARCHAR2
)
AS
    V_ID     NUMBER;
    V_EXISTE NUMBER;
BEGIN
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'EDITAR_PRODUCTO');

    BEGIN
        SELECT ID_PROVEEDOR INTO V_ID
        FROM PROVEEDORES
        WHERE ID_PROVEEDOR = P_ID_PROVEEDOR;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20049, 'El proveedor no existe.');
    END;

    SELECT COUNT(*) INTO V_EXISTE
    FROM PROVEEDORES
    WHERE LOWER(NOMBRE_PROVEEDOR) = LOWER(P_NOMBRE_PROVEEDOR)
      AND ID_PROVEEDOR <> P_ID_PROVEEDOR;

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20048, 'Ya existe un proveedor con ese nombre.');
    END IF;

    UPDATE PROVEEDORES
    SET NOMBRE_PROVEEDOR = P_NOMBRE_PROVEEDOR,
        NOMBRE_CONTACTO  = P_NOMBRE_CONTACTO,
        TELEFONO         = P_TELEFONO,
        DIRECCION        = P_DIRECCION
    WHERE ID_PROVEEDOR = P_ID_PROVEEDOR;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/
