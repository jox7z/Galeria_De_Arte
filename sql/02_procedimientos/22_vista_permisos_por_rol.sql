CREATE OR REPLACE VIEW VW_PERMISOS_POR_ROL AS
SELECT 
    R.ID_ROL,
    R.NOMBRE_ROL,
    R.DESCRIPCION_ROL,
    P.ID_PERMISO,
    P.NOMBRE_PERMISO,
    P.DESCRIPCION_PERMISO
FROM ROLES R
LEFT JOIN PERMISOS_ROLES PR ON R.ID_ROL = PR.ID_ROL
LEFT JOIN PERMISOS P ON PR.ID_PERMISO = P.ID_PERMISO
ORDER BY R.ID_ROL, P.ID_PERMISO;
/
