CREATE OR REPLACE PROCEDURE DESHABILITAR_USUARIO(
    P_ID_USUARIO_ACCION IN NUMBER,
    P_ID_USUARIO        IN NUMBER
)
AS
    V_ID_USUARIO NUMBER;
BEGIN
    SP_VALIDAR_PERMISO(P_ID_USUARIO_ACCION, 'INHABILITAR_USUARIO');

    BEGIN
        SELECT ID_USUARIO INTO V_ID_USUARIO
        FROM USUARIOS
        WHERE ID_USUARIO = P_ID_USUARIO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20015, 'El usuario no existe.');
    END;
    
    UPDATE USUARIOS
    SET ESTADO = 'INACTIVO'
    WHERE ID_USUARIO = P_ID_USUARIO;

   EXCEPTION
       WHEN OTHERS THEN
        RAISE; -- Re-lanzar el error
END;
/
