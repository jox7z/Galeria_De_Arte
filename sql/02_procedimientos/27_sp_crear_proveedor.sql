CREATE OR REPLACE PROCEDURE SP_CREAR_PROVEEDOR(
    P_ID_USUARIO        IN  NUMBER,
    P_NOMBRE_PROVEEDOR  IN  VARCHAR2,
    P_NOMBRE_CONTACTO   IN  VARCHAR2,
    P_TELEFONO          IN  VARCHAR2,
    P_DIRECCION         IN  VARCHAR2,
    P_ID_PROVEEDOR_OUT  OUT NUMBER
)
AS
    V_EXISTE NUMBER;
BEGIN
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'CREAR_PRODUCTO');

    IF P_NOMBRE_PROVEEDOR IS NULL THEN
        RAISE_APPLICATION_ERROR(-20047, 'El nombre del proveedor es obligatorio.');
    END IF;

    SELECT COUNT(*) INTO V_EXISTE
    FROM PROVEEDORES
    WHERE LOWER(NOMBRE_PROVEEDOR) = LOWER(P_NOMBRE_PROVEEDOR);

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20048, 'Ya existe un proveedor con ese nombre.');
    END IF;

    INSERT INTO PROVEEDORES (NOMBRE_PROVEEDOR, NOMBRE_CONTACTO, TELEFONO, DIRECCION)
    VALUES (P_NOMBRE_PROVEEDOR, P_NOMBRE_CONTACTO, P_TELEFONO, P_DIRECCION)
    RETURNING ID_PROVEEDOR INTO P_ID_PROVEEDOR_OUT;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/
