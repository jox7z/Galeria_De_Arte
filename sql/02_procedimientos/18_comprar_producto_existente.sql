CREATE OR REPLACE PROCEDURE COMPRAR_PRODUCTO_EXISTENTE(
    P_ID_USUARIO IN NUMBER,
    P_ID_PRODUCTO IN NUMBER,
    P_COSTO            IN NUMBER,
    P_CANTIDAD         IN NUMBER
)
AS
    V_ID_PROVEEDOR NUMBER;
    V_ID_PRODUCTO NUMBER;
BEGIN
    --VALIDACIONES---
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'EDITAR_PRODUCTO');
    
    BEGIN
        SELECT ID_PRODUCTO INTO V_ID_PRODUCTO
        FROM PRODUCTOS
        WHERE ID_PRODUCTO = P_ID_PRODUCTO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20015, 'El producto no existe.');
    END;
    
    UPDATE PRODUCTOS
    SET
        COSTO = P_COSTO,
        CANTIDAD = CANTIDAD + P_CANTIDAD
    WHERE ID_PRODUCTO = P_ID_PRODUCTO;

    EXCEPTION
       WHEN OTHERS THEN
        ROLLBACK; -- Primero hacer rollback
        RAISE; -- Re-lanzar el error
END;
/
