CREATE OR REPLACE TYPE T_LISTA_PERMISOS AS TABLE OF NUMBER;
/
T_LISTA_PERMISOS(1,2,3,5);--EJ DE USO

CREATE OR REPLACE PROCEDURE CREAR_ROL(
    P_ID_USUARIO       IN NUMBER,
    P_NOMBRE_ROL       IN VARCHAR2,
    P_DESCRIPCION_ROL  IN VARCHAR2,
    P_PERMISOS         IN T_LISTA_PERMISOS
)
AS
    V_ID_ROL NUMBER;
    V_EXISTE NUMBER;
BEGIN
    -- VALIDAR PERMISO DEL USUARIO QUE ESTÁ CREANDO
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'CREAR_ROL');

    -- VALIDAR NOMBRE ÚNICO
    SELECT COUNT(*) INTO V_EXISTE
    FROM ROLES
    WHERE NOMBRE_ROL = P_NOMBRE_ROL;

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(-20050, 'El nombre de rol ya existe.');
    END IF;

    -- CREAR ROL
    INSERT INTO ROLES (NOMBRE_ROL, DESCRIPCION_ROL)
    VALUES (P_NOMBRE_ROL, P_DESCRIPCION_ROL)
    RETURNING ID_ROL INTO V_ID_ROL;

    -- ASIGNAR PERMISOS
    IF P_PERMISOS IS NOT NULL THEN
        FOR I IN 1 .. P_PERMISOS.COUNT LOOP
        
            -- Verificar que el permiso existe
            SELECT COUNT(*)
            INTO V_EXISTE
            FROM PERMISOS
            WHERE ID_PERMISO = P_PERMISOS(I);

            IF V_EXISTE = 0 THEN
                RAISE_APPLICATION_ERROR(-20051, 'El permiso ' || P_PERMISOS(I) || ' no existe.');
            END IF;

            -- Insertar asignación
            INSERT INTO PERMISOS_ROLES (ID_ROL, ID_PERMISO)
            VALUES (V_ID_ROL, P_PERMISOS(I));
        END LOOP;
    END IF;
END;
/
