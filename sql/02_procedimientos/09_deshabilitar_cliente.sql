CREATE OR REPLACE PROCEDURE DESHABILITAR_CLIENTE(
    P_ID_USUARIO IN NUMBER,
    P_ID_CLIENTE IN NUMBER
)
AS
    V_ID_CLIENTE NUMBER;
BEGIN
    --VALIDACIONES---
    SP_VALIDAR_PERMISO(P_ID_USUARIO, 'INHABILITAR_CLIENTE');
    
    BEGIN
        SELECT ID_CLIENTE INTO V_ID_CLIENTE
        FROM CLIENTES
        WHERE ID_CLIENTE = P_ID_CLIENTE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20015, 'El cliente no existe.');
    END;
    
    UPDATE CLIENTES
    SET ESTADO = 'INACTIVO'
    WHERE ID_CLIENTE = P_ID_CLIENTE;

    EXCEPTION
       WHEN OTHERS THEN
    RAISE; -- Re-lanzar el error
END;
/
