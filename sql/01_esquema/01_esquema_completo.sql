    -- 2. Validar que el usuario esté ACTIVO
    --------------------------------------------------
    SELECT ESTADO
    INTO V_ESTADO_USER
    FROM USUARIOS
    WHERE ID_USUARIO = P_ID_USUARIO;

    IF V_ESTADO_USER <> 'ACTIVO' THEN
        RAISE_APPLICATION_ERROR(-20031, 'El usuario no está activo.');
    END IF;

