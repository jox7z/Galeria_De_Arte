--  DDL for Trigger TRG_ALERTA_STOCK_BAJO
--------------------------------------------------------

  CREATE OR REPLACE NONEDITIONABLE TRIGGER "GALERIAARTE"."TRG_ALERTA_STOCK_BAJO" 
AFTER UPDATE OF CANTIDAD ON PRODUCTOS
FOR EACH ROW
 WHEN (NEW.CANTIDAD < NEW.STOCK_MINIMO) DECLARE
    v_alerta_existe NUMBER;
    v_diferencia NUMBER;
    v_nivel_prioridad VARCHAR2(20);
BEGIN
    -- Calcular cuántas unidades faltan para llegar al mínimo
    v_diferencia := :NEW.STOCK_MINIMO - :NEW.CANTIDAD;

    -- Determinar nivel de prioridad
    IF :NEW.CANTIDAD = 0 THEN
        v_nivel_prioridad := '¡CRÍTICO!';
    ELSIF v_diferencia > 10 THEN
        v_nivel_prioridad := 'ALTO';
    ELSIF v_diferencia > 5 THEN
        v_nivel_prioridad := 'MEDIO';
    ELSE
        v_nivel_prioridad := 'BAJO';
    END IF;

    -- Verificar si ya existe una alerta activa para este producto
    SELECT COUNT(*)
    INTO v_alerta_existe
    FROM ALERTAS_STOCK
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
      AND ESTADO_ALERTA = 'ACTIVA';

    -- Si no existe alerta activa, crear una nueva
    IF v_alerta_existe = 0 THEN
        INSERT INTO ALERTAS_STOCK (
            ID_PRODUCTO,
            STOCK_ACTUAL,
            STOCK_MINIMO,
            DIFERENCIA,
            ESTADO_ALERTA
        ) VALUES (
            :NEW.ID_PRODUCTO,
            :NEW.CANTIDAD,
            :NEW.STOCK_MINIMO,
            v_diferencia,
            'ACTIVA'
        );

        -- MENSAJE DE ALERTA EN TERMINAL (solo cuando se crea la alerta por primera vez)
        DBMS_OUTPUT.PUT_LINE('');
        DBMS_OUTPUT.PUT_LINE('  ️  ALERTA DE STOCK BAJO [' || v_nivel_prioridad || ']');
        DBMS_OUTPUT.PUT_LINE('    Producto: ' || :NEW.NOMBRE_PRODUCTO || ' (' || :NEW.TIPO_PRODUCTO || ')');
        DBMS_OUTPUT.PUT_LINE('    Stock actual: ' || :NEW.CANTIDAD || ' | Mínimo: ' || :NEW.STOCK_MINIMO || ' | Faltan: ' || v_diferencia || ' unidades');
        DBMS_OUTPUT.PUT_LINE('    Recomendación: Contactar al proveedor para reabastecer');
        DBMS_OUTPUT.PUT_LINE('');
    ELSE
        -- Si ya existe, solo actualizar la información (sin mostrar mensaje repetido)
        UPDATE ALERTAS_STOCK
        SET STOCK_ACTUAL = :NEW.CANTIDAD,
            DIFERENCIA = v_diferencia,
            FECHA_ALERTA = SYSDATE
        WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
          AND ESTADO_ALERTA = 'ACTIVA';
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        -- Registrar error pero no bloquear la operación
        DBMS_OUTPUT.PUT_LINE('Error en trigger de alertas: ' || SQLERRM);
END;

/
ALTER TRIGGER "GALERIAARTE"."TRG_ALERTA_STOCK_BAJO" ENABLE;
