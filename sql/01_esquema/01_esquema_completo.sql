    JOIN PERMISOS_ROLES PR ON U.ID_ROL = PR.ID_ROL
    JOIN PERMISOS P        ON P.ID_PERMISO = PR.ID_PERMISO
    WHERE U.ID_USUARIO = P_ID_USUARIO
      AND UPPER(P.MODULO) = UPPER(P_MODULO);

    IF V_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20032,
            'Acceso denegado al módulo ' || P_MODULO || '.'
        );
    END IF;
END;

