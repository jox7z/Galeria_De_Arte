    SELECT COUNT(*)
    INTO V_COUNT
    FROM USUARIOS
    WHERE LOWER(CORREO_ELECTRONICO) = LOWER(P_CORREO);
    IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(-20008, 'El correo ya está registrado.');
