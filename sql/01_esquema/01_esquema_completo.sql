    -- 1. Validar que el usuario exista
    --------------------------------------------------
    SELECT COUNT(*)
    INTO V_COUNT
    FROM USUARIOS
    WHERE ID_USUARIO = P_ID_USUARIO;

    IF V_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20030, 'El usuario no existe.');
    END IF;

