  CREATE OR REPLACE NONEDITIONABLE TRIGGER "GALERIAARTE"."TRG_CALCULAR_TIEMPO_VISITA" 
BEFORE UPDATE OF HORA_SALIDA ON VISITANTES
FOR EACH ROW
BEGIN
    -- No permitir registrar salida más de una vez
    IF :OLD.HORA_SALIDA IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'La salida ya fue registrada anteriormente.');
    END IF;

    -- Registrar salida con fecha y hora completa
    :NEW.HORA_SALIDA := CAST(SYSTIMESTAMP AS DATE);

    -- Validar que la salida sea después de la entrada
    IF :NEW.HORA_SALIDA <= :OLD.HORA_ENTRADA THEN
        RAISE_APPLICATION_ERROR(-20002, 'La hora de salida no puede ser menor o igual que la hora de entrada.');
    END IF;

    -- Convertir la diferencia de fechas (NUMBER en días) en INTERVAL
    :NEW.TIEMPO_VISITA := NUMTODSINTERVAL(
        (:NEW.HORA_SALIDA - :OLD.HORA_ENTRADA),
        'DAY'
    );
END;

