        RAISE_APPLICATION_ERROR(-20002, 'Nombre y apellido son obligatorios.');
    END IF;
    IF P_NOMBRE_USUARIO IS NULL THEN
        RAISE_APPLICATION_ERROR(-20003, 'El nombre de usuario es obligatorio.');
    END IF;
    IF P_CORREO IS NULL THEN
        RAISE_APPLICATION_ERROR(-20004, 'El correo electrónico es obligatorio.');
    END IF;
    IF P_IDENTIFICACION IS NULL THEN
        RAISE_APPLICATION_ERROR(-20005, 'La identificación es obligatoria.');
