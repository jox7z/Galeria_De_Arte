) AS
    V_COUNT   NUMBER;
    V_HASH    VARCHAR2(200);
BEGIN
    -- 1. Campos obligatorios
    IF P_ID_ROL IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'El rol es obligatorio.');
    END IF;
